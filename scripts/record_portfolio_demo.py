#!/usr/bin/env python3
"""Record a silent, captioned walkthrough from a fresh native demo run.

The browser is a dedicated headless context. Its trace viewer replays the reports
generated by the same native executable used for the command shown on screen.
"""

from __future__ import annotations

import argparse
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
import json
import os
from pathlib import Path
import subprocess
import tempfile
import threading

from playwright.sync_api import expect, sync_playwright

ROOT = Path(__file__).resolve().parents[1]
SCENARIOS = {"recovered": "recovery-observed", "inconclusive": "inconclusive", "hostile": "boundary-held"}



class QuietHandler(SimpleHTTPRequestHandler):
    def log_message(self, *args: object) -> None:
        pass


def validate_run(server: Path, output: Path) -> str:
    environment = os.environ.copy()
    environment["PYTHONPATH"] = str(ROOT / "agent")
    server_arg = "./" + str(server.relative_to(ROOT))
    output_arg = "./" + str(output.relative_to(ROOT))
    command = ["python3", "-m", "native_mcp_agent", "demo", "--server", server_arg,
               "--output", output_arg]
    result = subprocess.run(command, cwd=ROOT, env=environment, text=True,
                            capture_output=True, timeout=90, check=False)
    if result.returncode:
        raise RuntimeError(f"native demonstration failed: {result.stderr.strip()}")
    if str(ROOT) in result.stdout:
        raise RuntimeError("native output unexpectedly contains a local workspace path")
    for name, outcome in SCENARIOS.items():
        current = json.loads((output / name / "report.json").read_text())
        published = json.loads((ROOT / "site/data" / name / "report.json").read_text())
        if current != published or current["result"] != outcome:
            raise RuntimeError(f"recorded viewer data differs from fresh native run: {name}")
    return result.stdout.strip()


def record(server: Path, destination: Path) -> None:
    server = server.resolve(strict=True)
    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="nms-reel-") as directory:
        scratch = Path(directory)
        output = ROOT / "build/portfolio-demo-run"
        terminal_output = validate_run(server, output)
        httpd = ThreadingHTTPServer(("127.0.0.1", 0),
                                    partial(QuietHandler, directory=str(ROOT / "site")))
        thread = threading.Thread(target=httpd.serve_forever, daemon=True)
        thread.start()
        try:
            with sync_playwright() as playwright:
                browser = playwright.chromium.launch(headless=True)
                context = browser.new_context(viewport={"width": 1600, "height": 900},
                                              device_scale_factor=1,
                                              record_video_dir=str(scratch / "video"),
                                              record_video_size={"width": 1600, "height": 900})
                page = context.new_page()
                errors: list[str] = []
                page.on("pageerror", lambda error: errors.append(str(error)))
                page.goto(f"http://127.0.0.1:{httpd.server_port}/")
                expect(page.locator("#outcome")).to_have_text("recovery-observed")
                page.add_style_tag(url=f"http://127.0.0.1:{httpd.server_port}/assets/reel.css")
                page.evaluate("""() => {
                  const caption = document.createElement('div'); caption.id='reel-caption';
                  caption.innerHTML='<span class="reel-kicker"></span><span class="reel-title"></span><span class="reel-detail"></span>';
                  document.body.append(caption);
                  const cover=document.createElement('div'); cover.id='reel-cover';
                  cover.innerHTML='<span class="reel-brand">N/ NATIVE MCP SANDBOX</span><h1></h1><p></p><div class="reel-rule"></div>';
                  document.body.append(cover);
                  const terminal=document.createElement('div'); terminal.id='reel-terminal'; terminal.hidden=true;
                  terminal.innerHTML='<div class="term-head"><span>LOCAL LINUX RUN · SYNTHETIC EVIDENCE</span><span>native-mcp-sandbox / stdio</span></div><h2>One command. Three evidence outcomes.</h2><pre></pre><div class="note">Real native process and shipped Python client. No hosted model or API key.</div>';
                  document.body.append(terminal);
                }""")

                def caption(chapter: str, title: str, detail: str) -> None:
                    page.evaluate("""([chapter,title,detail]) => {
                      document.querySelector('#reel-caption .reel-kicker').textContent=chapter;
                      document.querySelector('#reel-caption .reel-title').textContent=title;
                      document.querySelector('#reel-caption .reel-detail').textContent=detail;
                    }""", [chapter, title, detail])

                def cover(title: str, detail: str, seconds: int) -> None:
                    page.evaluate("""([title,detail]) => {
                      const cover=document.querySelector('#reel-cover');
                      cover.querySelector('h1').textContent=title;
                      cover.querySelector('p').textContent=detail;
                      cover.hidden=false; document.querySelector('#reel-terminal').hidden=true;
                      document.querySelector('#reel-caption').hidden=true;
                    }""", [title, detail])
                    page.wait_for_timeout(seconds * 1000)

                def show_site() -> None:
                    page.evaluate("""() => {
                      document.querySelector('#reel-cover').hidden=true;
                      document.querySelector('#reel-terminal').hidden=true;
                      document.querySelector('#reel-caption').hidden=false;
                    }""")

                def hold(seconds: int) -> None:
                    page.wait_for_timeout(seconds * 1000)

                def scroll_to(selector: str, offset: int = 88) -> None:
                    page.locator(selector).evaluate(
                        "(element,offset) => window.scrollTo({top:element.offsetTop-offset,behavior:'instant'})",
                        offset)
                    hold(1)

                cover("Inspect Linux evidence without giving an AI a shell.",
                      "A recorded end-to-end investigation through a C++20 MCP authority boundary.", 7)
                cover("The operator sets the scope. The native server enforces it.",
                      "Four read-only tools. Approved roots and process aliases. Bounded work and output.", 7)
                show_site()
                caption("01 / THE BOUNDARY", "The client can propose. C++ decides what it may inspect.",
                        "The native process has no shell, provider SDK or network client.")
                hold(9)

                command = ("$ python3 -m native_mcp_agent demo \\\n"
                           "  --server ./build/release/native-mcp-sandbox \\\n"
                           "  --output ./build/portfolio-demo-run")
                page.evaluate("""(value) => {
                  const t=document.querySelector('#reel-terminal'); t.hidden=false;
                  t.querySelector('pre').textContent=value;
                  document.querySelector('#reel-caption').hidden=true;
                }""", command)
                hold(5)
                page.locator("#reel-terminal pre").evaluate(
                    "(element,value) => element.textContent=value", command + "\n\n" + terminal_output)
                hold(12)

                show_site()
                scroll_to("#investigation", 55)
                caption("02 / RECOVERY OBSERVED", "The log records recovery after retries.",
                        "The report cites validated logs.search and logs.tail responses, rather than provider text.")
                hold(8)
                page.locator('[data-evidence="e1"]').click()
                caption("02 / EVIDENCE", "Open the exact native response behind the claim.",
                        "The viewer shows bounded arguments, a correlated response ID and validated result fields.")
                hold(8)
                page.locator('[data-evidence="e2"]').click()
                hold(6)

                page.locator('[data-scenario="inconclusive"]').click()
                expect(page.locator("#outcome")).to_have_text("inconclusive")
                caption("03 / UNCERTAINTY", "Incomplete evidence stays inconclusive.",
                        "The search hits its match cap, and the ELF header disagrees with the deployment target.")
                hold(9)
                page.locator('[data-evidence="e3"]').click()
                hold(6)

                page.locator('[data-scenario="hostile"]').click()
                expect(page.locator("#outcome")).to_have_text("boundary-held")
                caption("04 / HOSTILE REQUESTS", "Two proposals cross two different boundaries.",
                        "C++ rejects ../outside.txt; Python rejects the invented shell.exec tool.")
                hold(10)
                page.locator('[data-evidence="e5"]').click()
                page.evaluate("window.scrollBy({top: 155, behavior: 'instant'})")
                caption("04 / NATIVE DENIAL", "The forbidden path reaches C++ and is denied there.",
                        "The native result reports invalid_relative_path. No file outside the approved root is read.")
                hold(9)
                page.locator(".control-trace summary").click()
                caption("04 / CONTROL TRACE", "Every proposal, authorization and response is traceable.",
                        "The hostile proposals are scripted; this demonstrates enforcement, not live-model immunity.")
                hold(8)

                scroll_to("#measurements", 42)
                caption("05 / MEASURED COST", "The native boundary has measured resource costs.",
                        "Raw samples, fixture hashes and build settings are included; no unsupported speedup claim.")
                hold(11)
                scroll_to("#engineering", 42)
                caption("06 / ENGINEERING", "Inspect the Linux mechanisms beneath the API.",
                        "Descriptor containment, bounded stdio, two workers and a fixed admission cap.")
                hold(9)
                scroll_to("#reproduce", 42)
                caption("07 / REPRODUCE", "Run the same three scenarios on Linux.",
                        "The demo needs strict openat2 and pidfd support, and no provider credential.")
                hold(9)
                cover("Watch the evidence. Reproduce the boundary.",
                      "github.com/kabbersokhi-boop/native-mcp-sandbox", 7)

                if errors:
                    raise RuntimeError("browser errors during recording: " + "; ".join(errors))
                video = page.video
                context.close()
                source = Path(video.path())
                subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(source),
                                "-c:v", "libx264", "-preset", "medium", "-crf", "23",
                                "-pix_fmt", "yuv420p", "-movflags", "+faststart", str(destination)],
                               check=True, timeout=180)
                browser.close()
        finally:
            httpd.shutdown()
            httpd.server_close()
            thread.join(timeout=2)
    print(f"Recorded {destination}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--server", type=Path, default=ROOT / "build/release/native-mcp-sandbox")
    parser.add_argument("--output", type=Path, default=ROOT / "site/assets/portfolio-demo.mp4")
    arguments = parser.parse_args()
    record(arguments.server, arguments.output)
